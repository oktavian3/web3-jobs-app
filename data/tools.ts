export function getToolInfo(name: string) {
  const normalized = name.toLowerCase();
  const exact = tools.find((tool) => tool.name.toLowerCase() === normalized);
  if (exact) return exact;
  const officialUrl = officialToolUrls[normalized];
  if (!officialUrl) return undefined;
  return {
    name,
    category: "Role tool",
    purpose: `Official tool or source used in ${name}-related Web3 workflows.`,
    roleUsage: "Use it to produce, verify, coordinate, document, or publish role-specific work.",
    practicalExample: `Include ${name} in a portfolio artifact with the workflow, assumptions, and final output clearly documented.`,
    officialUrl,
    learnResourceUrl: "/learn-web3",
  };
}
